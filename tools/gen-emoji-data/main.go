// Command gen-emoji-data turns Unicode's emoji-test.txt into the emoji
// picker's data file (emoji_data.go in the repository root).
//
// Usage, from the repository root:
//
//	curl -sSfLo /tmp/emoji-test.txt https://unicode.org/Public/emoji/latest/emoji-test.txt
//	go run ./tools/gen-emoji-data -o emoji_data.go /tmp/emoji-test.txt
//
// Only "fully-qualified" lines are kept. The "Component" group is skipped,
// and so is the "Flags" group, because terminals do not draw flags.
// Sequences terminals draw with inconsistent widths are left out: anything
// with a skin tone modifier (U+1F3FB to U+1F3FF), a zero width joiner
// (U+200D) or a keycap (U+20E3). The input is treated as untrusted:
// malformed lines are skipped, and names are limited to printable ASCII.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"os"
	"strconv"
	"strings"
)

// groups are the emoji-test.txt groups the picker shows, in picker order.
// "Component" and "Flags" are not among them.
var groups = []string{
	"Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink",
	"Travel & Places", "Activities", "Objects", "Symbols",
}

// sourceURL is where emoji-test.txt is published.
const sourceURL = "https://unicode.org/Public/emoji/latest/emoji-test.txt"

func main() {
	out := flag.String("o", "emoji_data.go", "output Go file")
	flag.Parse()
	if flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: gen-emoji-data [-o emoji_data.go] path/to/emoji-test.txt")
		os.Exit(2)
	}
	in, err := os.Open(flag.Arg(0))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer in.Close()
	data, err := generate(in)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, data, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// excluded reports whether a sequence is left out of the picker.
func excluded(cps []rune) bool {
	for _, r := range cps {
		switch {
		case r >= 0x1F3FB && r <= 0x1F3FF, r == 0x200D, r == 0x20E3:
			return true
		}
	}
	return false
}

// validName accepts printable ASCII without the backtick that would end the
// raw string literal.
func validName(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < 0x20 || s[i] > 0x7E || s[i] == '`' {
			return false
		}
	}
	return true
}

// generate reads emoji-test.txt and returns the Go source of the data file.
func generate(r io.Reader) ([]byte, error) {
	want := map[string]bool{}
	for _, g := range groups {
		want[g] = true
	}
	byGroup := map[string][]string{}
	seen := map[string]bool{}
	version, date := "", ""
	group := ""
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 64*1024), 1024*1024)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		switch {
		case strings.HasPrefix(line, "# Version:"):
			version = strings.TrimSpace(strings.TrimPrefix(line, "# Version:"))
			continue
		case strings.HasPrefix(line, "# Date:"):
			date = strings.TrimSpace(strings.TrimPrefix(line, "# Date:"))
			continue
		case strings.HasPrefix(line, "# group:"):
			group = strings.TrimSpace(strings.TrimPrefix(line, "# group:"))
			continue
		case line == "" || strings.HasPrefix(line, "#"):
			continue
		}
		if !want[group] {
			continue
		}
		fields, comment, ok := strings.Cut(line, "#")
		if !ok {
			continue
		}
		cpField, status, ok := strings.Cut(fields, ";")
		if !ok || strings.TrimSpace(status) != "fully-qualified" {
			continue
		}
		var cps []rune
		bad := false
		for _, h := range strings.Fields(cpField) {
			v, err := strconv.ParseUint(h, 16, 32)
			if err != nil || v > 0x10FFFF {
				bad = true
				break
			}
			cps = append(cps, rune(v))
		}
		if bad || len(cps) == 0 || excluded(cps) {
			continue
		}
		// Comment: "<emoji> E<version> <name>".
		c := strings.Fields(comment)
		if len(c) < 3 || !strings.HasPrefix(c[1], "E") {
			continue
		}
		name := strings.Join(c[2:], " ")
		if !validName(name) {
			continue
		}
		e := string(cps)
		key := strings.ReplaceAll(e, "️", "")
		if seen[key] {
			continue
		}
		seen[key] = true
		byGroup[group] = append(byGroup[group], e+"\t"+name)
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if version == "" {
		return nil, fmt.Errorf("no \"# Version:\" line; is this emoji-test.txt?")
	}
	for _, g := range groups {
		if len(byGroup[g]) == 0 {
			return nil, fmt.Errorf("group %q is empty", g)
		}
	}
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: AGPL-3.0-only\n\n")
	b.WriteString("// Code generated by \"go run ./tools/gen-emoji-data -o emoji_data.go emoji-test.txt\"; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: %s (Emoji %s, %s).\n", sourceURL, version, date)
	b.WriteString("// Fully-qualified emoji only; the Component and Flags groups (terminals do\n")
	b.WriteString("// not draw flags) and skin tone, ZWJ and keycap sequences are left out.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("// emojiDataVersion is the Emoji version of emoji-test.txt the data was made from.\n")
	fmt.Fprintf(&b, "const emojiDataVersion = %q\n\n", version)
	b.WriteString("// emojiData lists the emoji picker's emoji: a line \"# <group>\" starts a\n")
	b.WriteString("// group, every other line is \"<emoji>\\t<CLDR name>\", in CLDR order.\n")
	b.WriteString("const emojiData = `")
	for _, g := range groups {
		b.WriteString("# " + g + "\n")
		for _, l := range byGroup[g] {
			b.WriteString(l + "\n")
		}
	}
	b.WriteString("`\n")
	return []byte(b.String()), nil
}
